    private void btnGuardarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnGuardarActionPerformed
    String idSiniestro = txtIdSiniestro.getText().trim();
    String descBien    = txtBienDescripcion.getText().trim();
    String tipoBien    = cbxTipoBien.getSelectedItem().toString();
    String nombreRiesgo = cbxTipoRiesgo.getSelectedItem().toString();
    String nombreAseg   = cbxAseguradora.getSelectedItem().toString();
    String fecha        = txtFecha.getText().trim();
    String montoTexto   = txtMonto.getText().trim();
    String zona         = cbxZona.getSelectedItem().toString();
    String descripcion  = txtDescripcion.getText().trim();
    String idCliente    = cbxIdCliente.getSelectedItem().toString();

    // Validaciones básicas (igual que antes)
    if (idSiniestro.isEmpty() || descBien.isEmpty() || nombreRiesgo.isEmpty() ||
        nombreAseg.isEmpty() || fecha.isEmpty() || montoTexto.isEmpty() ||
        zona.isEmpty() || descripcion.isEmpty()) {
        JOptionPane.showMessageDialog(this,
            "Por favor, llene todos los campos antes de guardar.");
        return;
    }

    double monto;
    try {
        monto = Double.parseDouble(montoTexto);
    } catch (NumberFormatException ex) {
        JOptionPane.showMessageDialog(this,
            "El monto del siniestro debe ser numérico.");
        return;
    }

    try {
        // AQUÍ se obtiene idBien y si hay SQLException se va directo al catch de abajo
        String idBien        = obtenerOCrearIdBien(descBien, tipoBien, idCliente);
        String idRiesgo      = obtenerIdRiesgoPorNombre(nombreRiesgo);
        String idAseguradora = obtenerIdAseguradoraPorNombre(nombreAseg);

        if (idRiesgo == null || idAseguradora == null) {
            JOptionPane.showMessageDialog(this,
                "Error: no se encontraron los IDs correspondientes en la base de datos.");
            return;
        }

        conexion con = new conexion();
        Connection cn = con.getConnection();
        Statement st = cn.createStatement();

        String sql = "INSERT INTO `siniestros/eventos` " +
                     "(idSiniestro, idBien, idRiesgo, idAseguradora, fecha, monto, zona, descripcion) " +
                     "VALUES ('" + idSiniestro + "', '" + idBien + "', '" + idRiesgo + "', '" +
                     idAseguradora + "', '" + fecha + "', " + monto + ", '" + zona + "', '" +
                     descripcion + "')";
        int filas = st.executeUpdate(sql);

        if (filas > 0) {
            JOptionPane.showMessageDialog(this,
                "Siniestro registrado correctamente.");
            limpiarCampos();
        } else {
            JOptionPane.showMessageDialog(this,
                "No se pudo registrar el siniestro.");
        }
    } catch (SQLException ex) {
        JOptionPane.showMessageDialog(this,
            "Error al registrar el siniestro: " + ex.getMessage());
    }
    
    }//GEN-LAST:event_btnGuardarActionPerformed

