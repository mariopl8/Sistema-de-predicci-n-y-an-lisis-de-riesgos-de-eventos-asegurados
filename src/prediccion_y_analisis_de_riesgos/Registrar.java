    private String obtenerOCrearIdBien(String descripcionBien, String tipoBien, String idCliente) throws SQLException {
    conexion con = new conexion();
    Connection cn = con.getConnection();
    Statement st = cn.createStatement();

    // 1) Buscar si ya existe un bien con esa descripción para ese cliente
    String sqlBusca = "SELECT idBien FROM bienes " +
                      "WHERE descripcion = '" + descripcionBien + "' " +
                      "AND idCliente = '" + idCliente + "'";
    ResultSet rs = st.executeQuery(sqlBusca);
    if (rs.next()) {
        return rs.getString("idBien");
    }

    // 2) No existe: generar nuevo idBien
    String sqlMax = "SELECT MAX(idBien) FROM bienes";
    ResultSet rsMax = st.executeQuery(sqlMax);
    String nuevoId;
    if (rsMax.next() && rsMax.getString(1) != null) {
        String ultimo = rsMax.getString(1);       // ej. "B0000008"
        int num = Integer.parseInt(ultimo.substring(1)); // quita la 'B'
        num++;
        nuevoId = String.format("B%07d", num);    // B + 7 dígitos
    } else {
        nuevoId = "B0000001";
    }

    String sqlInserta = "INSERT INTO bienes (idBien, idCliente, descripcion, valorAsegurado, tipoBien) " +
                        "VALUES ('" + nuevoId + "', '" + idCliente + "', '" + descripcionBien +
                        "', 0, '" + tipoBien + "')";
    st.executeUpdate(sqlInserta);

    return nuevoId;
}

    

// Busca idRiesgo a partir del nombre del riesgo
private String obtenerIdRiesgoPorNombre(String nombreRiesgo) throws SQLException {
    conexion con = new conexion();
    Connection cn = con.getConnection();
    String sql = "SELECT idRiesgo FROM tiposRiesgo WHERE nombreRiesgo = '" + nombreRiesgo + "'";
    Statement st = cn.createStatement();
    ResultSet rs = st.executeQuery(sql);
    return rs.next() ? rs.getString("idRiesgo") : null;
}

// Busca idAseguradora a partir del nombre
private String obtenerIdAseguradoraPorNombre(String nombreAseg) throws SQLException {
    conexion con = new conexion();
    Connection cn = con.getConnection();
    String sql = "SELECT idAseguradora FROM aseguradoras WHERE nombre = '" + nombreAseg + "'";
    Statement st = cn.createStatement();
    ResultSet rs = st.executeQuery(sql);
    return rs.next() ? rs.getString("idAseguradora") : null;
}



