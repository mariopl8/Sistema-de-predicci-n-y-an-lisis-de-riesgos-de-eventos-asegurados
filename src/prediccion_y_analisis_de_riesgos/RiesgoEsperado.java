    private void btnMedirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnMedirActionPerformed
        String nombreRiesgo = cbxTipoRiesgo.getSelectedItem().toString();

    try {
        // 1. Obtener el idRiesgo real desde la tabla tiposRiesgo
        String idRiesgo = obtenerIdRiesgoPorNombre(nombreRiesgo);
        if (idRiesgo == null) {
            JOptionPane.showMessageDialog(this,
                "No se encontró el tipo de riesgo seleccionado en la tabla tiposRiesgo.");
            return;
        }

        conexion con = new conexion();
        Connection cn = con.getConnection();
        Statement st = cn.createStatement();

        // 2. Contar cuántos siniestros corresponden a ese riesgo
        ResultSet rs1 = st.executeQuery(
            "SELECT COUNT(*) FROM `siniestros/eventos` WHERE idRiesgo = '" + idRiesgo + "'");
        rs1.next();
        double nRiesgo = rs1.getInt(1);

        // 3. Contar el total de siniestros de la base
        ResultSet rs2 = st.executeQuery(
            "SELECT COUNT(*) FROM `siniestros/eventos`");
        rs2.next();
        double nTotal = rs2.getInt(1);

        // 4. Calcular la severidad promedio (monto promedio) para ese riesgo
        ResultSet rs3 = st.executeQuery(
            "SELECT AVG(monto) FROM `siniestros/eventos` WHERE idRiesgo = '" + idRiesgo + "'");
        rs3.next();
        double severidadProm = rs3.getDouble(1);

        // Validación por si aún no hay datos suficientes
        if (nTotal == 0 || nRiesgo == 0) {
            JOptionPane.showMessageDialog(this,
                "No hay siniestros suficientes para calcular el riesgo esperado para " + nombreRiesgo + ".");
            return;
        }

        // 5. Frecuencia (probabilidad estimada) = siniestros de ese riesgo / total de siniestros
        double prob = nRiesgo / nTotal;

        // 6. Riesgo esperado = frecuencia × severidad promedio
        double riesgoEsperado = prob * severidadProm;

        // 7. Mostrar resultado al usuario
        JOptionPane.showMessageDialog(this,
            "Para el riesgo \"" + nombreRiesgo + "\" (" + idRiesgo + "):" +
            "\nFrecuencia = " + prob +
            "\nSeveridad promedio = " + severidadProm +
            "\nRiesgo esperado = " + riesgoEsperado);
    } catch (SQLException ex) {
        // En caso de error de conexión o SQL, se informa en un cuadro de diálogo
        JOptionPane.showMessageDialog(this,
            "Error al calcular el riesgo esperado: " + ex.getMessage());
    }                                  

    }//GEN-LAST:event_btnMedirActionPerformed

