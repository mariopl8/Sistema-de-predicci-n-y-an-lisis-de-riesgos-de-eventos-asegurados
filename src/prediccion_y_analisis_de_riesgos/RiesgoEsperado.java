    private String obtenerIdRiesgoPorNombre(String nombreRiesgo) throws SQLException {
    conexion con = new conexion();
    Connection cn = con.getConnection();
    String sql = "SELECT idRiesgo FROM tiposRiesgo WHERE nombreRiesgo = '" + nombreRiesgo + "'";
    Statement st = cn.createStatement();
    ResultSet rs = st.executeQuery(sql);
    if (rs.next()) {
        return rs.getString("idRiesgo");
    } else {
        return null;
    }
}


